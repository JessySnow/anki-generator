def clean_v3_word(word_raw: str, reading_raw: str) -> tuple[str, str]:
    w = word_raw.strip()
    r = reading_raw.strip()
    # Normalize slashes in words like 抑える/押さえる
    if "/" in r or "／" in r:
        r = re.split(r"[/／]", r)[0].strip()
    return w, r

def load_normalized_words() -> list[dict]:
    """Parse all 556 entries from Selected Notes.txt with canonical lemma and readings."""
    with open(SELECTED_NOTES_PATH, "r", encoding="utf-8") as f:
        lines = [l.strip("\n") for l in f if l.strip() and not l.startswith("#")]

    with open(GRAMMAR_PATH, "r", encoding="utf-8") as f:
        grammar_list = json.load(f).get("grammar_list", [])
    grammar_count = len(grammar_list)

    # Load POS cache if present
    pos_cache = {}
    if POS_CACHE_PATH.exists():
        try:
            with open(POS_CACHE_PATH, "r", encoding="utf-8") as f:
                pos_cache = json.load(f)
        except Exception:
            pos_cache = {}

    words_data = []
    for idx, line in enumerate(lines):
        parts = line.split("\t")
        guid = parts[0]
        nt = parts[1]
        deck = parts[2]
        meaning = parts[3].strip()
        tags = parts[9].strip() if len(parts) > 9 else ""

        if guid in V2_GUID_CANONICAL:
            w, r, p, m, n = V2_GUID_CANONICAL[guid]
            meaning = m if m else meaning
        elif nt == "日文单词V3":
            raw_w = re.sub(r"\[sound:[^\]]+\]", "", parts[4]).strip()
            raw_r = parts[5].strip()
            p = parts[6].strip()
            w, r = clean_v3_word(raw_w, raw_r)
            n = ""
        else:
            raw_w = re.sub(r"\[sound:[^\]]+\]", "", parts[4]).strip()
            p = parts[5].strip()
            w, r = raw_w, raw_w
            n = ""

        # Check POS cache for standard enriched POS
        clean_key = w.strip()
        if clean_key in pos_cache:
            p = pos_cache[clean_key].get("mapped_pos", p)

        # Generate Ruby Furigana
        furi = lib.generate_furigana(w, r)

        # Pair with immutable grammar point
        g_entry = grammar_list[idx % grammar_count]

        words_data.append({
            "word_index": idx,
            "guid": guid,
            "notetype": "Japanese N2 Vocab & Grammar",
            "deck": deck,
            "word": w,
            "reading": r,
            "furigana": furi,
            "pos": p,
            "meaning": meaning,
            "collocation_note": n,
            "grammar_id": g_entry["id"],
            "grammar_pattern": g_entry["pattern"],
            "grammar_meaning": g_entry["meaning"],
            "original_tags": tags
        })
    return words_data

def split_into_batches(words_data: list[dict]):
    """Split 556 words into 10 batches under N3_4_Level/batches/."""
    BATCHES_DIR.mkdir(parents=True, exist_ok=True)
    batch_size = 56 # 56 * 9 = 504, 10th batch = 52
    for b_idx in range(1, 11):
        start = (b_idx - 1) * batch_size
        end = min(b_idx * batch_size, len(words_data)) if b_idx < 10 else len(words_data)
        b_words = words_data[start:end]
        batch_file = BATCHES_DIR / f"batch_{b_idx:02d}.json"
        with open(batch_file, "w", encoding="utf-8") as f:
            json.dump({
                "batch_number": b_idx,
                "count": len(b_words),
                "start_index": start,
                "end_index": end - 1,
                "words": b_words
            }, f, ensure_ascii=False, indent=2)
    print(f"Generated 10 batch files in {BATCHES_DIR}")

def main():
    words_data = load_normalized_words()
    WORDS_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(WORDS_OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump({"total": len(words_data), "vocabulary_list": words_data}, f, ensure_ascii=False, indent=2)
    print(f"Successfully generated {len(words_data)} clean entries in {WORDS_OUTPUT_PATH}")

    split_into_batches(words_data)

if __name__ == "__main__":
    main()
