def main():
    batch_path = REPO_ROOT / "N3_4_Level" / "batches" / "batch_06.json"
    with open(batch_path, "r", encoding="utf-8") as f:
        batch_raw = json.load(f)

    words = batch_raw["words"]
    print(f"Loaded {len(words)} words from {batch_path}")

    cards = []
    recorded_count = 0

    for item in words:
        w_idx = item["word_index"]
        if w_idx not in BATCH_06_DATA:
            raise KeyError(f"Missing linguistic data for word_index {w_idx} ({item['word']})")

        ling = BATCH_06_DATA[w_idx]

        orig_tags = item.get("original_tags", "").strip()
        tags_parts = ["N3_4::Vocabulary", f"N3_4::Grammar::{item['grammar_id']}"]
        if orig_tags:
            tags_parts.append(orig_tags)
        tags_str = " ".join(tags_parts)

        card = {
            "guid": item["guid"],
            "word_index": w_idx,
            "Word": item["word"],
            "Reading": item["reading"],
            "Furigana": item["furigana"],
            "POS": item["pos"],
            "Meaning": item["meaning"],
            "WordAudio": "",
            "Sentence": ling["Sentence"],
            "SentenceAudio": "",
            "SentenceTranslation": ling["SentenceTranslation"],
            "WordUsage": ling["WordUsage"],
            "GrammarPattern": item["grammar_pattern"],
            "GrammarMeaning": ling["GrammarMeaning"],
            "GrammarUsage": ling["GrammarUsage"],
            "CombinationLogic": ling["CombinationLogic"],
            "Tags": tags_str,
        }

        ok, msg = record_n3_4_card.record_card(card)
        if not ok:
            print(f"ERROR recording card #{w_idx:04d}: {msg}", file=sys.stderr)
            sys.exit(1)

        cards.append(card)
        recorded_count += 1

    print(f"Successfully recorded all {recorded_count} cards into N3_4_Level/progress/cards/.")

    # Save to generated_batch_06.json as well
    out_batch_file = REPO_ROOT / "N3_4_Level" / "batches" / "generated_batch_06.json"
    with open(out_batch_file, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"Saved generated batch to {out_batch_file}")

if __name__ == "__main__":
    main()
