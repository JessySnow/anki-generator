def main():
    batch_path = REPO_ROOT / "N3_4_Level" / "batches" / "batch_03.json"
    with open(batch_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    words = data["words"] if isinstance(data, dict) and "words" in data else data

    print(f"Loaded {len(words)} raw items from {batch_path}")
    print(f"Loaded {len(BATCH_03_DATA)} crafted linguistic entries")

    cards = []
    recorded_count = 0

    for item in words:
        w_idx = item["word_index"]
        if w_idx not in BATCH_03_DATA:
            print(f"ERROR: missing data for word_index {w_idx} ({item.get('word')})", file=sys.stderr)
            sys.exit(1)

        c_info = BATCH_03_DATA[w_idx]

        orig_tags = item.get("original_tags", "").strip()
        tag_parts = ["N3_4::Vocabulary", f"N3_4::Grammar::{item['grammar_id']}"]
        if orig_tags:
            tag_parts.append(orig_tags)
        tags_str = " ".join(tag_parts)

        card = {
            "guid": item["guid"],
            "word_index": w_idx,
            "Word": item["word"],
            "Reading": item["reading"],
            "Furigana": item["furigana"],
            "POS": item["pos"],
            "Meaning": item["meaning"],
            "WordAudio": "",
            "Sentence": c_info["Sentence"],
            "SentenceAudio": "",
            "SentenceTranslation": c_info["SentenceTranslation"],
            "WordUsage": c_info["WordUsage"],
            "GrammarPattern": item["grammar_pattern"],
            "GrammarMeaning": c_info["GrammarMeaning"],
            "GrammarUsage": c_info["GrammarUsage"],
            "CombinationLogic": c_info["CombinationLogic"],
            "Tags": tags_str
        }

        # Validate card using record_n3_4_card
        ok, msg = record_n3_4_card.record_card(card)
        if not ok:
            print(f"Failed to record card {w_idx:04d}: {msg}", file=sys.stderr)
            sys.exit(1)
        
        recorded_count += 1
        cards.append(card)

    print(f"Successfully recorded all {recorded_count} cards into N3_4_Level/progress/cards/!")

    # Save to generated_batch_03.json
    generated_path = REPO_ROOT / "N3_4_Level" / "batches" / "generated_batch_03.json"
    with open(generated_path, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"Successfully saved {len(cards)} cards to {generated_path}")

if __name__ == "__main__":
    main()
