def main():
    batch_file = REPO_ROOT / "N3_4_Level" / "batches" / "batch_01.json"
    with open(batch_file, "r", encoding="utf-8") as f:
        batch_info = json.load(f)

    words_map = {w["word_index"]: w for w in batch_info["words"]}

    print(f"Loaded {len(words_map)} words from {batch_file}")

    success_count = 0
    for item in BATCH_01_DATA:
        idx = item["word_index"]
        if idx not in words_map:
            print(f"Error: index {idx} not in batch_01.json", file=sys.stderr)
            return 1
        
        raw_word = words_map[idx]

        tags = f"N3_4::Vocabulary N3_4::Grammar::{raw_word['grammar_id']} {raw_word['original_tags']}".strip()

        card = {
            "word_index": idx,
            "guid": raw_word["guid"],
            "Word": raw_word["word"],
            "Reading": raw_word["reading"],
            "Furigana": raw_word["furigana"],
            "POS": raw_word["pos"],
            "Meaning": raw_word["meaning"],
            "Sentence": item["Sentence"],
            "SentenceTranslation": item["SentenceTranslation"],
            "WordUsage": item["WordUsage"],
            "GrammarPattern": item["GrammarPattern"],
            "GrammarMeaning": item["GrammarMeaning"],
            "GrammarUsage": item["GrammarUsage"],
            "CombinationLogic": item["CombinationLogic"],
            "WordAudio": "",
            "SentenceAudio": "",
            "Tags": tags,
        }

        ok, msg = record_n3_4_card.record_card(card)
        if not ok:
            print(f"Failed to record card {idx:04d}: {msg}", file=sys.stderr)
            return 1
        success_count += 1
        print(f"Successfully recorded card {idx:04d}: {card['Word']} ({msg})")

    print(f"\nAll {success_count} cards for Batch 01 successfully generated and recorded!")
    return 0

if __name__ == "__main__":
    sys.exit(main())
