def main():
    batch_file = REPO_ROOT / "N3_4_Level" / "batches" / "batch_07.json"
    with open(batch_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    words = data["words"]
    print(f"Loaded {len(words)} words from {batch_file}")

    if len(words) != 56:
        print(f"Warning: expected 56 words, got {len(words)}")

    cards = []
    for item in words:
        idx = item["word_index"]
        if idx not in CARDS_DATA:
            print(f"Error: missing CARDS_DATA for index {idx} ({item['word']})", file=sys.stderr)
            sys.exit(1)

        c_info = CARDS_DATA[idx]
        orig_tags = item.get("original_tags", "").strip()
        tags_str = f"N3_4::Vocabulary N3_4::Grammar::{item['grammar_id']}"
        if orig_tags:
            tags_str += f" {orig_tags}"

        card = {
            "guid": item["guid"],
            "word_index": idx,
            "Word": item["word"],
            "Reading": item["reading"],
            "Furigana": item["furigana"],
            "POS": item["pos"],
            "Meaning": item["meaning"],
            "WordAudio": "",
            "Sentence": c_info["Sentence"],
            "SentenceAudio": "",
            "SentenceTranslation": c_info["SentenceTranslation"],
            "WordUsage": c_info["WordUsage"],
            "GrammarPattern": item["grammar_pattern"],
            "GrammarMeaning": c_info["GrammarMeaning"],
            "GrammarUsage": c_info["GrammarUsage"],
            "CombinationLogic": c_info["CombinationLogic"],
            "Tags": tags_str
        }

        cards.append(card)

    print(f"Constructed {len(cards)} cards. Validating and recording...")

    # Record cards using record_n3_4_card.record_card
    for card in cards:
        ok, msg = record_n3_4_card.record_card(card)
        if not ok:
            print(f"Error recording card #{card['word_index']:04d}: {msg}", file=sys.stderr)
            sys.exit(1)
        print(msg)

    # Save to workspace generated batch 07
    ws_target = REPO_ROOT / "N3_4_Level" / "batches" / "generated_batch_07.json"
    with open(ws_target, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"Saved all {len(cards)} cards to {ws_target}")

if __name__ == "__main__":
    main()
