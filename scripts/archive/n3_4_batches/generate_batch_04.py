def main():
    batch_path = REPO_ROOT / "N3_4_Level" / "batches" / "batch_04.json"
    with open(batch_path, "r", encoding="utf-8") as f:
        raw_data = json.load(f)

    raw_words = raw_data["words"]
    print(f"Loaded {len(raw_words)} raw words from {batch_path}")
    print(f"Loaded {len(BATCH_04_DATA)} linguistic entries in BATCH_04_DATA")

    cards = []
    recorded_count = 0

    for item in raw_words:
        w_idx = item["word_index"]
        if w_idx not in BATCH_04_DATA:
            print(f"ERROR: missing linguistic entry for word_index {w_idx} ({item.get('word')})", file=sys.stderr)
            sys.exit(1)

        c_info = BATCH_04_DATA[w_idx]

        orig_tags = item.get("original_tags", "").strip()
        tag_parts = ["N3_4::Vocabulary", f"N3_4::Grammar::{item['grammar_id']}"]
        if orig_tags:
            tag_parts.append(orig_tags)
        tags_str = " ".join(tag_parts)

        card = {
            "guid": item["guid"],
            "word_index": w_idx,
            "Word": item["word"],
            "Reading": item["reading"],
            "Furigana": item["furigana"],
            "POS": item["pos"],
            "Meaning": item["meaning"],
            "WordAudio": "",
            "Sentence": c_info["Sentence"],
            "SentenceAudio": "",
            "SentenceTranslation": c_info["SentenceTranslation"],
            "WordUsage": c_info["WordUsage"],
            "GrammarPattern": c_info["GrammarPattern"],
            "GrammarMeaning": c_info["GrammarMeaning"],
            "GrammarUsage": c_info["GrammarUsage"],
            "CombinationLogic": c_info["CombinationLogic"],
            "Tags": tags_str,
        }

        # Validate required fields
        required = [
            "guid", "word_index", "Word", "Reading", "Furigana", "POS", "Meaning",
            "Sentence", "SentenceTranslation", "WordUsage",
            "GrammarPattern", "GrammarMeaning", "GrammarUsage", "CombinationLogic", "Tags"
        ]
        for r in required:
            val = card.get(r)
            if val is None or str(val).strip() == "":
                print(f"ERROR: Card {w_idx:04d} missing required field '{r}'", file=sys.stderr)
                sys.exit(1)

        cards.append(card)

        # Record card into N3_4_Level/progress/cards/{idx:04d}.json
        ok, msg = record_n3_4_card.record_card(card)
        if not ok:
            print(f"ERROR recording card {w_idx:04d}: {msg}", file=sys.stderr)
            sys.exit(1)
        recorded_count += 1

    print(f"Successfully recorded all {recorded_count} cards into N3_4_Level/progress/cards/!")

    # Also save to N3_4_Level/batches/generated_batch_04.json for batch tracking
    target_batch = REPO_ROOT / "N3_4_Level" / "batches" / "generated_batch_04.json"
    with open(target_batch, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"Successfully wrote {len(cards)} cards to {target_batch}")

if __name__ == "__main__":
    main()
