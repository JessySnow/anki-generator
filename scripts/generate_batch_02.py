def main():
    batch_path = REPO_ROOT / "N3_4_Level" / "batches" / "batch_02.json"
    with open(batch_path, "r", encoding="utf-8") as f:
        batch = json.load(f)

    words = batch["words"]
    print(f"Loaded {len(words)} raw items from {batch_path}")
    print(f"Linguistic data contains {len(BATCH_02_DATA)} entries")

    if len(words) != len(BATCH_02_DATA):
        print(f"ERROR: count mismatch ({len(words)} vs {len(BATCH_02_DATA)})")
        sys.exit(1)

    cards = []
    for item in words:
        w_idx = item["word_index"]
        if w_idx not in BATCH_02_DATA:
            print(f"ERROR: missing data for word_index {w_idx} ({item.get('word')})")
            sys.exit(1)

        c_info = BATCH_02_DATA[w_idx]

        orig_tags = item.get("original_tags", "").strip()
        tags = f"N3_4::Vocabulary N3_4::Grammar::{item['grammar_id']} {orig_tags}".strip()

        card = {
            "guid": item["guid"],
            "word_index": w_idx,
            "Word": item["word"],
            "Reading": item["reading"],
            "Furigana": item["furigana"],
            "POS": item["pos"],
            "Meaning": item["meaning"],
            "WordAudio": "",
            "Sentence": c_info["Sentence"],
            "SentenceAudio": "",
            "SentenceTranslation": c_info["SentenceTranslation"],
            "WordUsage": c_info["WordUsage"],
            "GrammarPattern": item["grammar_pattern"],
            "GrammarMeaning": c_info["GrammarMeaning"],
            "GrammarUsage": c_info["GrammarUsage"],
            "CombinationLogic": c_info["CombinationLogic"],
            "Tags": tags
        }

        # Validate required fields
        required = [
            "guid", "word_index", "Word", "Reading", "Furigana", "POS", "Meaning",
            "Sentence", "SentenceTranslation", "WordUsage",
            "GrammarPattern", "GrammarMeaning", "GrammarUsage", "CombinationLogic", "Tags"
        ]
        for r in required:
            val = card.get(r)
            if val is None or (isinstance(val, str) and val.strip() == ""):
                print(f"ERROR: Card #{w_idx:04d} missing required field '{r}'")
                sys.exit(1)

        # Record card
        ok, msg = record_n3_4_card.record_card(card)
        if not ok:
            print(f"ERROR recording card #{w_idx:04d}: {msg}")
            sys.exit(1)
        print(f"✓ {msg}")

        cards.append(card)

    print(f"\nAll {len(cards)} cards successfully recorded to N3_4_Level/progress/cards/!")

    # Update generated_batch_02.json for consistency
    out_file = REPO_ROOT / "N3_4_Level" / "batches" / "generated_batch_02.json"
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"Saved generated batch to {out_file}")

if __name__ == "__main__":
    main()
