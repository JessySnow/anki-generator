# Special reading fixes for items that were misparsed in the raw import
READING_OVERRIDES = {
    433: ("ざらざら", "ざらざら"),
    436: ("さんざん", "さんざん"),
}

def main():
    batch_file = REPO_ROOT / "N3_4_Level" / "batches" / "batch_08.json"
    with open(batch_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    words = data.get("words", data) if isinstance(data, dict) else data
    print(f"Loaded {len(words)} words from {batch_file}")

    cards = []
    for item in words:
        w_idx = item["word_index"]
        if w_idx not in LINGUISTIC_DATA:
            raise KeyError(f"Missing linguistic data for word_index {w_idx} ({item.get('word')})")

        ling = LINGUISTIC_DATA[w_idx]

        reading = item["reading"]
        furigana = item["furigana"]
        if w_idx in READING_OVERRIDES:
            reading, furigana = READING_OVERRIDES[w_idx]

        orig_tags = item.get("original_tags", "").strip()
        tags_str = f"N3_4::Vocabulary N3_4::Grammar::{item['grammar_id']}"
        if orig_tags:
            tags_str = f"{tags_str} {orig_tags}"

        card = {
            "guid": item["guid"],
            "word_index": w_idx,
            "Word": item["word"],
            "Reading": reading,
            "Furigana": furigana,
            "POS": item["pos"],
            "Meaning": item["meaning"],
            "WordAudio": "",
            "Sentence": ling["Sentence"],
            "SentenceAudio": "",
            "SentenceTranslation": ling["SentenceTranslation"],
            "WordUsage": ling["WordUsage"],
            "GrammarPattern": item["grammar_pattern"],
            "GrammarMeaning": ling["GrammarMeaning"],
            "GrammarUsage": ling["GrammarUsage"],
            "CombinationLogic": ling["CombinationLogic"],
            "Tags": tags_str.strip()
        }

        # Validate card fields
        required = [
            "guid", "word_index", "Word", "Reading", "Furigana", "POS", "Meaning",
            "Sentence", "SentenceTranslation", "WordUsage",
            "GrammarPattern", "GrammarMeaning", "GrammarUsage", "CombinationLogic", "Tags"
        ]
        for r in required:
            if card.get(r) is None or str(card[r]).strip() == "":
                raise ValueError(f"Card #{w_idx:04d} has missing/empty required field '{r}'")

        if card["WordAudio"] != "" or card["SentenceAudio"] != "":
            raise ValueError(f"Card #{w_idx:04d} audio fields must be strictly empty string")

        cards.append(card)

    print(f"Validated all {len(cards)} cards successfully.")

    # Record each card using record_n3_4_card
    saved_count = 0
    for card in cards:
        ok, msg = record_n3_4_card.record_card(card)
        if not ok:
            print(f"Error recording card #{card['word_index']:04d}: {msg}", file=sys.stderr)
            sys.exit(1)
        saved_count += 1

    print(f"Recorded {saved_count} cards to N3_4_Level/progress/cards/")

    # Also update generated_batch_08.json
    out_file = REPO_ROOT / "N3_4_Level" / "batches" / "generated_batch_08.json"
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"Saved complete batch to {out_file}")

if __name__ == "__main__":
    main()
